/// Strips diacritical marks from a string using the literal three-step
/// algorithm from `../fuse-js/src/helpers/diacritics.ts`:
/// 1. NFD-normalize.
/// 2. Remove every scalar in the combining-mark range table (pasted verbatim
///    from the upstream regex at `../fuse-js/src/helpers/diacritics.ts:25`).
/// 3. Apply `NON_DECOMPOSABLE_MAP` for chars that survive NFD unchanged.
///
/// `String.folding(options: .diacriticInsensitive)` is **not** used; it relies
/// on ICU and diverges from upstream on real inputs.
enum Diacritics {
    static func strip(_ str: String) -> String {
        let nfd = str.decomposedStringWithCanonicalMapping
        var output = ""
        output.reserveCapacity(nfd.unicodeScalars.count)
        for scalar in nfd.unicodeScalars {
            if isCombiningMark(scalar.value) { continue }
            if let mapped = nonDecomposableMap[scalar.value] {
                output += mapped
            } else {
                output.unicodeScalars.append(scalar)
            }
        }
        return output
    }

    /// 12-entry table from `../fuse-js/src/helpers/diacritics.ts:2-15`. Chars
    /// that survive NFD unchanged and need explicit mapping.
    private static let nonDecomposableMap: [UInt32: String] = [
        0x0142: "l",  // ł
        0x0141: "L",  // Ł
        0x0111: "d",  // đ
        0x0110: "D",  // Đ
        0x00F8: "o",  // ø
        0x00D8: "O",  // Ø
        0x0127: "h",  // ħ
        0x0126: "H",  // Ħ
        0x0167: "t",  // ŧ
        0x0166: "T",  // Ŧ
        0x0131: "i",  // ı
        0x00DF: "ss", // ß
    ]

    private static func isCombiningMark(_ value: UInt32) -> Bool {
        var lo = 0
        var hi = combiningMarkRanges.count
