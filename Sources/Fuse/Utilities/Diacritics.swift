            let mid = (lo + hi) >> 1
            let range = combiningMarkRanges[mid]
            if value < range.lowerBound {
                hi = mid
            } else if value > range.upperBound {
                lo = mid + 1
            } else {
                return true
            }
        }
        return false
    }

